// Embeds lib/knowledge.json at build time and writes lib/embeddings.generated.ts,
// so the server does not spend API quota on it at every cold start.
// Never fails the build: without a key, or on an API error, it leaves the placeholder in place.
import { readFileSync, writeFileSync } from "node:fs";
import { GoogleGenAI } from "@google/genai";

const OUT = new URL("../lib/embeddings.generated.ts", import.meta.url);
const chunks = JSON.parse(readFileSync(new URL("../lib/knowledge.json", import.meta.url), "utf8"));

// Same hash as knowledgeHash() in lib/knowledge.ts.
function hash(list) {
  let h = 2166136261;
  for (const c of list) for (const ch of `${c.id}\n${c.title}\n${c.text}\n`) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return h.toString(16);
}
const normalize = (v) => { const n = Math.sqrt(v.reduce((s, x) => s + x * x, 0)) || 1; return v.map((x) => +(x / n).toFixed(6)); };

if (!process.env.GEMINI_API_KEY) {
  console.log("[build-index] GEMINI_API_KEY not set, skipping (embeddings will be computed at runtime)");
  process.exit(0);
}
try {
  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
  const res = await ai.models.embedContent({
    model: "gemini-embedding-001",
    contents: chunks.map((c) => `${c.title}\n${c.text}`),
    config: { taskType: "RETRIEVAL_DOCUMENT", outputDimensionality: 768 },
  });
  const vectors = res.embeddings.map((e) => normalize(e.values));
  writeFileSync(
    OUT,
    `// Generated by scripts/build-index.mjs at build time. Do not edit.\nexport const PREBUILT: { hash: string; vectors: number[][] } | null = ${JSON.stringify({ hash: hash(chunks), vectors })};\n`
  );
  console.log(`[build-index] embedded ${vectors.length} chunks`);
} catch (e) {
  console.warn(`[build-index] failed, embeddings will be computed at runtime: ${e?.status ?? ""} ${String(e?.message ?? e).slice(0, 200)}`);
}
